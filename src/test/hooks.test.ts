const INV: Invocation = { command: "/usr/bin/node", args: ["/opt/baton/dist/cli.js"] };

test("install claude: merges with user hooks, idempotent, uninstall restores", async () => {
  const { home } = sandbox();
  const file = path.join(home, "settings.json");
  const userHook = { matcher: "Bash", hooks: [{ type: "command", command: "echo mine" }] };
  writeFileSync(file, JSON.stringify({ model: "x", hooks: { PreToolUse: [userHook], Stop: [{ hooks: [{ type: "command", command: "say done" }] }] } }));

  assert.equal(await installClaude(file, INV), "installed");
  const s = JSON.parse(readFileSync(file, "utf8"));
  assert.equal(s.model, "x");
  assert.deepEqual(s.hooks.PreToolUse, [userHook]);
  assert.equal(s.hooks.Stop.length, 2); // user's + ours
  assert.deepEqual(s.hooks.SessionStart[0].hooks[0].args, ["/opt/baton/dist/cli.js", "hook", "claude"]);
  assert.equal(s.hooks.Stop[1].hooks[0].async, true);
  assert.ok(existsSync(file + ".baton-backup"));

  assert.equal(await installClaude(file, INV), "unchanged");
  assert.equal(await installClaude(file, { ...INV, command: "/new/node" }), "updated");
  assert.equal(JSON.parse(readFileSync(file, "utf8")).hooks.SessionStart.length, 1);

  assert.equal(await uninstallClaude(file), "removed");
  const after = JSON.parse(readFileSync(file, "utf8"));
  assert.deepEqual(after.hooks, { PreToolUse: [userHook], Stop: [{ hooks: [{ type: "command", command: "say done" }] }] });
  assert.equal(await uninstallClaude(file), "absent");
});

test("install claude: refuses to touch invalid JSON", async () => {
  const { home } = sandbox();
  const file = path.join(home, "settings.json");
  writeFileSync(file, "{ not json");
  await assert.rejects(installClaude(file, INV), /not valid JSON/);
  assert.equal(readFileSync(file, "utf8"), "{ not json");
});

test("install opencode: writes plugin, refuses foreign file", async () => {
  const { home } = sandbox();
  const file = path.join(home, "plugins", "baton.js");
  assert.equal(await installOpencode(file, INV), "installed");
  assert.equal(await installOpencode(file, INV), "unchanged");
  assert.equal(await uninstallOpencode(file), "removed");
  writeFileSync(file, "export const Mine = async () => ({})");
  await assert.rejects(installOpencode(file, INV), /not generated by baton/);
  assert.equal(await uninstallOpencode(file), "absent");
});

test("opencode plugin: valid module; detached stop capture and start context wired to baton", async () => {
  const { home } = sandbox();
  // A stand-in for baton's cli.js that records how it was called.
  const recorder = path.join(home, "fake-cli.mjs");
  const record = path.join(home, "calls.txt");
  writeFileSync(recorder, `import { appendFileSync } from "node:fs"; appendFileSync(${JSON.stringify(record)}, JSON.stringify(process.argv.slice(2)) + "\\n");`);
  const file = path.join(home, "baton-plugin.mjs");
  writeFileSync(file, opencodePluginSource({ command: process.execPath, args: [recorder] }));
  const mod = await import(pathToFileURL(file).href);

  const shellCalls: string[][] = [];
  // Minimal stand-in for Bun's `$`: records argv, returns a chainable ShellPromise-like.
  const $ = (strings: TemplateStringsArray, ...values: unknown[]) => {
    const argv: string[] = [];
    strings.forEach((s, i) => {
      argv.push(...s.split(/\s+/).filter(Boolean));
      if (i < values.length) {
        const v = values[i];
        argv.push(...(Array.isArray(v) ? v.map(String) : [String(v)]));
      }
    });
    shellCalls.push(argv);
    const result = Promise.resolve({ exitCode: 0, stdout: Buffer.from("[baton] handoff note\n") });
    const chain: any = { quiet: () => chain, nothrow: () => chain, then: result.then.bind(result), catch: result.catch.bind(result) };
    return chain;
  };

  const hooks = await mod.BatonPlugin({ $, directory: home });
  await hooks.event({ event: { type: "session.idle", properties: { sessionID: "ses_1" } } });
  await hooks.event({ event: { type: "message.updated", properties: {} } });
  // Send side runs as a detached process (survives `opencode run` exiting): wait for it.
  for (let i = 0; i < 50 && !existsSync(record); i++) await new Promise((r) => setTimeout(r, 100));
  assert.deepEqual(JSON.parse(readFileSync(record, "utf8").trim()), [
    "hook", "opencode", "--event", "session.idle", "--session", "ses_1", "--root", home,
  ]);
  assert.equal(shellCalls.length, 0);

  // Receive side goes through `$` and is awaited (its stdout becomes system prompt text).
  const out = { system: [] as string[] };
  await hooks["experimental.chat.system.transform"]({ sessionID: "ses_1" }, out);
  await hooks["experimental.chat.system.transform"]({ sessionID: "ses_1" }, out);
  assert.deepEqual(out.system, ["[baton] handoff note", "[baton] handoff note"]);
  assert.equal(shellCalls.length, 1); // start check runs once per session
  assert.deepEqual(shellCalls[0]!.slice(1), [recorder, "hook", "opencode", "--event", "start", "--session", "ses_1", "--root", home]);
});

test("hook start: an aborted session of this agent does not hide the handoff", async () => {
  const sb = handoffFixture();
  await initProject(sb.project);
  // Claude was started again after Codex but failed before doing anything (e.g. quota error).
  writeJsonl(path.join(sb.dirs.claudeProjects, encodeProjectDir(sb.project), "aborted.jsonl"), [
    { type: "user", cwd: sb.project, message: { content: "continue" } },
  ]);
  const text = await runHook({ agent: "claude", event: "start", cwd: sb.project, sessionId: "new" }, ctxOf(sb.dirs));
  assert.match(text, /Handoff detected: codex/);
});

/** Claude used the project yesterday, Codex worked after it and hit its limit. */
function handoffFixture() {
  const sb = sandbox();
  const claudeFile = path.join(sb.dirs.claudeProjects, encodeProjectDir(sb.project), "old-claude.jsonl");
  writeJsonl(claudeFile, [
    { type: "user", cwd: sb.project, message: { content: "set up the project" } },
    { type: "assistant", cwd: sb.project, message: { content: [{ type: "text", text: "done" }] } },
  ]);
  const old = new Date(Date.now() - 86_400_000);
  utimesSync(claudeFile, old, old);

  writeJsonl(path.join(sb.dirs.codexSessions[0]!, "2026", "rollout-x.jsonl"), [
    { type: "session_meta", payload: { id: "codex-1", cwd: sb.project, thread_source: "user" } },
    { type: "event_msg", payload: { type: "task_started" } },
    { type: "event_msg", payload: { type: "item_completed", item: { type: "UserMessage", content: [{ type: "text", text: "add OAuth login" }] } } },
    { type: "event_msg", payload: { type: "item_completed", item: { type: "AgentMessage", content: [{ type: "Text", text: "Adding the OAuth callback route." }] } } },
    { type: "event_msg", payload: { type: "token_count", rate_limits: { primary: { used_percent: 100 } } } },
  ]);
  return { ...sb, claudeFile };
}

test("hook start: injects handoff from a more recent other agent", async () => {
  const sb = handoffFixture();
  // not initialised -> no-op
  assert.equal(await runHook({ agent: "claude", event: "start", cwd: sb.project, sessionId: "new" }, ctxOf(sb.dirs)), "");

  await initProject(sb.project);
  const text = await runHook({ agent: "claude", event: "start", cwd: sb.project, sessionId: "new" }, ctxOf(sb.dirs));
  assert.match(text, /Handoff detected: codex/);
  assert.match(text, /add OAuth login/);
  assert.match(readFileSync(path.join(sb.project, ".baton", "RESUME.md"), "utf8"), /from a \*\*codex\*\* session/);
  assert.ok((await readCaptures(sb.project))["codex:codex-1"]);

  // From Codex's point of view nothing changed hands: Codex is the most recent agent.
  assert.equal(await runHook({ agent: "codex" as any, event: "start", cwd: sb.project }, ctxOf(sb.dirs)), "");
});

test("hook stop: captures the agent's own session once per version", async () => {
  const sb = handoffFixture();
  await initProject(sb.project);
  const input = { agent: "claude" as const, event: "stop" as const, cwd: sb.project, sessionId: "old-claude", transcriptPath: sb.claudeFile };
  assert.equal(await runHook(input, ctxOf(sb.dirs)), "");
  const resume = path.join(sb.project, ".baton", "RESUME.md");
  assert.match(readFileSync(resume, "utf8"), /from a \*\*claude\*\* session/);
  assert.ok(existsSync(path.join(sb.project, ".baton", "checkpoints", "session_claude_d-claude.md")));

  writeFileSync(resume, "sentinel");
  await runHook(input, ctxOf(sb.dirs)); // transcript unchanged -> skipped
  assert.equal(readFileSync(resume, "utf8"), "sentinel");
});
