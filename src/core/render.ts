import type { Action, Checkpoint } from "./extract.js";
import type { GitInfo } from "./git.js";
import { redact } from "./redact.js";
import { clip, oneLine } from "./text.js";

const STATUS_MARK: Record<string, string> = {
  completed: "[x]",
  in_progress: "[~]",
  pending: "[ ]",
  cancelled: "[-]",
};

function quote(text: string, max: number): string {
  return clip(text, max)
    .split("\n")
    .map((l) => `> ${l}`)
    .join("\n");
}

function fence(text: string): string {
  const longest = Math.max(2, ...[...text.matchAll(/`+/g)].map((m) => m[0].length));
  const f = "`".repeat(longest + 1);
  return `${f}\n${text}\n${f}`;
}

function actionLine(a: Action): string {
  const mark = a.pending ? "…" : a.ok === false ? "✗" : a.ok === true ? "✓" : "·";
  return `- ${mark} \`${a.name}\` ${oneLine(a.input, 140)}`;
}

/** Render a checkpoint (+ git state) to the RESUME.md markdown handed to the next agent. */
export function renderCheckpoint(cp: Checkpoint, git: GitInfo | undefined, generatedAt = new Date()): string {
  const s = cp.session;
  const out: string[] = [];
  out.push("# Baton handoff: resume here");
  out.push("");
  out.push(
    `> Generated by \`baton\` at ${generatedAt.toISOString()} from a **${s.agent}** session${s.env ? ` in ${s.env}` : ""}` +
      ` (\`${s.id}\`${s.title ? `, "${oneLine(s.title, 80)}"` : ""}), last active ${s.updatedAt}.`,
  );
  out.push(
    "> This snapshot is mechanically extracted from the transcript and may be incomplete. " +
      "Treat it as a lead, and verify against the code and `git` before acting.",
  );
  out.push("");
  out.push("## How to continue");
  out.push("1. Read `.baton/STATE.md` (long-lived project state) if it exists.");
  out.push("2. Read this file, especially **Where it stopped** and **Todo**.");
  out.push("3. Check `git status` / `git diff` to see the real state of the code.");
  out.push("4. Update `.baton/STATE.md` with anything important from here, then continue the work.");
  out.push("");

  if (s.clone) {
    out.push("## ⚠ Different clone");
    out.push(
      `This session ran in **another clone** of this repository: \`${s.clone.root}\`` +
        (s.clone.branch ? ` (branch \`${s.clone.branch}\`)` : "") +
        ". Its uncommitted work is **not** in this working tree. Have it committed and pushed there " +
        "(or fetch that branch here) before continuing; file paths below are relative to that clone.",
    );
    out.push("");
  }

  out.push("## Where it stopped");
  out.push(cp.interruption ? `- **${cp.interruption}**` : "- The session ended normally (last turn completed).");
  if (cp.quota) {
    const q = cp.quota;
    out.push(
      `- ${s.agent} quota: ${q.usedPercent}% used` +
        (q.windowMinutes ? ` of the ${Math.round(q.windowMinutes / 60)}h window` : "") +
        (q.resetsAt ? `, resets at ${q.resetsAt}` : ""),
    );
  }
  out.push(
    `- Session stats: ${s.userTurns} user turns, ${s.toolCalls} tool calls` +
      (s.compactions ? `, ${s.compactions} context compactions` : "") +
      (s.model ? `, model \`${s.model}\`` : ""),
  );
  out.push("");

  if (cp.goal.length) {
    out.push("## Original goal (first user messages)");
    for (const g of cp.goal) out.push(quote(g, 1200), "");
  }

  if (cp.recentRequests.length) {
    out.push("## Most recent user requests (oldest first)");
    for (const r of cp.recentRequests) out.push(quote(r, 800), "");
  }

  if (cp.todos?.length) {
    out.push("## Todo (last known)");
    for (const t of cp.todos) out.push(`- ${STATUS_MARK[t.status] ?? `[${t.status}]`} ${oneLine(t.content, 200)}`);
    out.push("");
  }

  if (cp.lastAssistant) {
    out.push("## Last assistant message");
    out.push(quote(cp.lastAssistant, 2000), "");
  }

  if (cp.errors.length) {
    out.push("## Recent failures (may since have been fixed; check)");
    for (const e of cp.errors) {
      out.push(actionLine(e));
      if (e.output.trim()) out.push("", fence(clip(e.output, 1200)), "");
    }
    out.push("");
  }

  if (cp.recentActions.length) {
    out.push("## Recent actions (oldest first)");
    out.push("Legend: ✓ ok, ✗ failed, … no result recorded, · unknown");
    for (const a of cp.recentActions) out.push(actionLine(a));
    const last = cp.recentActions[cp.recentActions.length - 1];
    if (last && !last.pending && last.output.trim()) {
      out.push("", "Output of the last action:", "", fence(clip(last.output, 1000)));
    }
    out.push("");
  }

  if (cp.filesTouched.length) {
    out.push("## Files modified in this session (most recent first)");
    for (const f of cp.filesTouched.slice(0, 40)) out.push(`- \`${f}\``);
    if (cp.filesTouched.length > 40) out.push(`- …and ${cp.filesTouched.length - 40} more`);
    out.push("");
  }

  out.push("## Git state at capture time");
  if (!git) {
    out.push("- Not a git repository.");
  } else {
    out.push(`- Branch: \`${git.branch ?? "(detached)"}\`${git.head ? `, HEAD: ${git.head}` : ""}`);
    if (git.status.length) {
      out.push("- Uncommitted changes:", "", fence(git.status.slice(0, 60).join("\n")));
    } else {
      out.push("- Working tree clean.");
    }
    if (git.diffStat) out.push("", "Diff vs HEAD:", "", fence(clip(git.diffStat, 2000)));
    if (git.recentCommits.length) out.push("", "Recent commits:", "", fence(git.recentCommits.join("\n")));
  }
  out.push("");

  return redact(out.join("\n"));
}
