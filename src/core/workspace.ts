// Everything baton writes inside the project lives here.
//   .baton/STATE.md        long-lived, agent-maintained project state (commit it)
//   .baton/RESUME.md       latest checkpoint for the next agent (gitignored)
//   .baton/checkpoints/    history of checkpoints (gitignored)
//   .baton/captures.json   which session versions were captured (gitignored)
//   .baton/hook.log        diagnostics from auto-capture hooks (gitignored)

import { existsSync } from "node:fs";
import { appendFile, mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import type { SessionRef } from "../model.js";

export const BATON_DIR = ".baton";
const MARK_START = "<!-- baton:start -->";
const MARK_END = "<!-- baton:end -->";

export function batonPaths(root: string) {
  const dir = path.join(root, BATON_DIR);
  return {
    dir,
    state: path.join(dir, "STATE.md"),
    resume: path.join(dir, "RESUME.md"),
    checkpoints: path.join(dir, "checkpoints"),
    gitignore: path.join(dir, ".gitignore"),
    captures: path.join(dir, "captures.json"),
    hookLog: path.join(dir, "hook.log"),
  };
}

export const STATE_TEMPLATE = `# Project State

<!-- Shared, long-lived memory for every coding agent working on this repo.
     Keep it short and current; rewrite sections rather than appending forever. -->

## Goal

## Current status

## Done

## In progress

## Next steps

## Decisions (and why)

## Gotchas
`;

export const AGENT_RULES = `${MARK_START}
## Multi-agent handoff (baton)

Several coding agents (Claude Code, Codex, opencode, ...) take turns on this project.
Shared progress lives in \`.baton/\`:

- **At the start of a session**, read \`.baton/STATE.md\`. If \`.baton/RESUME.md\` exists and is newer,
  read it too: it is a snapshot of exactly where the previous agent stopped. Verify it against
  \`git status\` / \`git diff\` before continuing, then merge what matters into \`STATE.md\`.
- **Keep \`.baton/STATE.md\` current**: after each meaningful step and before you stop, update
  status / done / in progress / next steps / decisions / gotchas. Be concise.
- Never write secrets into \`.baton/\`.
${MARK_END}`;

/** Insert or replace the baton block in a markdown file. Returns what happened. */
export async function upsertBlock(file: string, block: string): Promise<"created" | "updated" | "unchanged"> {
  if (!existsSync(file)) {
    await writeFile(file, block + "\n", "utf8");
    return "created";
  }
  const text = await readFile(file, "utf8");
  const start = text.indexOf(MARK_START);
  const end = text.indexOf(MARK_END);
  let next: string;
  if (start >= 0 && end > start) {
    next = text.slice(0, start) + block + text.slice(end + MARK_END.length);
  } else {
    next = text.replace(/\s*$/, "") + "\n\n" + block + "\n";
  }
  if (next === text) return "unchanged";
  await writeFile(file, next, "utf8");
  return "updated";
}

export interface InitResult {
  created: string[];
  updated: string[];
  unchanged: string[];
}

/** Idempotent project setup. */
export async function initProject(root: string): Promise<InitResult> {
  const p = batonPaths(root);
  const r: InitResult = { created: [], updated: [], unchanged: [] };
  const note = (file: string, what: "created" | "updated" | "unchanged") =>
    r[what].push(path.relative(root, file).replace(/\\/g, "/"));

  await mkdir(p.checkpoints, { recursive: true });
  if (!existsSync(p.state)) {
    await writeFile(p.state, STATE_TEMPLATE, "utf8");
    note(p.state, "created");
  } else note(p.state, "unchanged");

  note(p.gitignore, await ensureGitignore(p.gitignore));

  // AGENTS.md is read by Codex, opencode and most other agents.
  const agentsMd = path.join(root, "AGENTS.md");
  note(agentsMd, await upsertBlock(agentsMd, AGENT_RULES));

  // Claude Code reads CLAUDE.md; point it at AGENTS.md instead of duplicating rules.
  const claudeMd = path.join(root, "CLAUDE.md");
  if (!existsSync(claudeMd)) {
    await writeFile(claudeMd, "@AGENTS.md\n", "utf8");
    note(claudeMd, "created");
  } else {
    const text = await readFile(claudeMd, "utf8");
    if (/^@AGENTS\.md\s*$/m.test(text)) note(claudeMd, "unchanged");
    else note(claudeMd, await upsertBlock(claudeMd, AGENT_RULES));
  }
  return r;
}

const GITIGNORE_LINES = ["RESUME.md", "checkpoints/", "captures.json", "hook.log"];

/** Snapshots and local bookkeeping stay out of git; STATE.md is shared. */
async function ensureGitignore(file: string): Promise<"created" | "updated" | "unchanged"> {
  if (!existsSync(file)) {
    const body = "# generated by baton: snapshots are local, STATE.md is shared\n" + GITIGNORE_LINES.join("\n") + "\n";
    await writeFile(file, body, "utf8");
    return "created";
  }
  const text = await readFile(file, "utf8");
  const have = new Set(text.split(/\r?\n/).map((l) => l.trim()));
  const missing = GITIGNORE_LINES.filter((l) => !have.has(l));
  if (!missing.length) return "unchanged";
  await writeFile(file, text.replace(/\s*$/, "\n") + missing.join("\n") + "\n", "utf8");
  return "updated";
}

export function isInitialized(root: string): boolean {
  return existsSync(batonPaths(root).dir);
}

/** Persist a rendered checkpoint and make it the current RESUME.md. */
export async function saveCheckpoint(
  root: string,
  markdown: string,
  agent: string,
  sessionId: string,
  naming: "history" | "session" = "history",
): Promise<string> {
  const p = batonPaths(root);
  await mkdir(p.checkpoints, { recursive: true });
  const short = sessionId.replace(/[^A-Za-z0-9_-]/g, "").slice(-8);
  const name =
    naming === "session"
      ? `session_${agent}_${short}.md`
      : `${new Date().toISOString().replace(/[:.]/g, "-").slice(0, 19)}_${agent}_${short}.md`;
  const file = path.join(p.checkpoints, name);
  await writeFile(file, markdown, "utf8");
  await writeFile(p.resume, markdown, "utf8");
  return file;
}

/** Which session versions have already been captured: "agent:id" -> session updatedAt (ms). */
export type CaptureLog = Record<string, number>;

export async function readCaptures(root: string): Promise<CaptureLog> {
  try {
    return JSON.parse(await readFile(batonPaths(root).captures, "utf8"));
  } catch {
    return {};
  }
}

export async function recordCapture(root: string, ref: SessionRef): Promise<void> {
  const log = await readCaptures(root);
  log[`${ref.agent}:${ref.id}`] = ref.updatedAt.getTime();
  await writeFile(batonPaths(root).captures, JSON.stringify(log, null, 2) + "\n", "utf8");
}

/** Per-project preferences in .baton/config.json (committed, shared by everyone on the project). */
export interface ProjectConfig {
  /** "repo": also pick up sessions from other clones of this repository (e.g. Windows + WSL checkouts). */
  match?: "path" | "repo";
}

export async function readProjectConfig(root: string): Promise<ProjectConfig> {
  try {
    const c = JSON.parse(await readFile(path.join(batonPaths(root).dir, "config.json"), "utf8"));
    return c && typeof c === "object" ? c : {};
  } catch {
    return {};
  }
}

/** Hooks must stay silent towards the agent; their diagnostics go here. */
export async function hookLog(root: string, line: string): Promise<void> {
  try {
    await appendFile(batonPaths(root).hookLog, `${new Date().toISOString()} ${line}\n`, "utf8");
  } catch {
    /* never fail a hook because of logging */
  }
}
